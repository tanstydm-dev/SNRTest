//将32位数据转换至8位数据并按大端顺序存储
S32 BitDevideU32(U8 u8Buf[4], U32 u32Data)
{
	u8Buf[0] = (U8)((u32Data & 0xff000000u) >> 24);
	u8Buf[1] = (U8)((u32Data & 0x00ff0000u) >> 16);
	u8Buf[2] = (U8)((u32Data & 0x0000ff00u) >> 8);
	u8Buf[3] = (U8)(u32Data & 0x000000ffu);
	return 0;
}



/*	SFRBX协议 */
BOOL GetSFRBXPtl(const U8* pData, U32 dataLen, SSFRBX* pSFRBX)
{
	S32 n = 0;            //用于解析时的字节计数
	if (pData == NULL)    //输入值判断
	{
		return FALSE;
	}

	n += 6;          //跳过帧头
	memcpy(&pSFRBX->GNSSID, &pData[n], 1);
	n += 1;
	memcpy(&pSFRBX->SVID, &pData[n], 1);
	n += 1;
	memcpy(&pSFRBX->Reserved0, &pData[n], 1);
	n += 1;
	memcpy(&pSFRBX->FreqID, &pData[n], 1);
	n += 1;
	memcpy(&pSFRBX->numWords, &pData[n], 1);
	n += 1;
	memcpy(&pSFRBX->chn, &pData[n], 1);
	n += 1;
	memcpy(&pSFRBX->version, &pData[n], 1);
	n += 1;
	memcpy(&pSFRBX->Reserved1, &pData[n], 1);
	n += 1;

	/*	写入数据字 */
	for (S32 i = 0; i < pSFRBX->numWords; i++)
	{
		memcpy(&pSFRBX->dwrd[i], &pData[n], 4);
		n += 4;
	}






	return TRUE;
}

#define	GET_BIT(x, bit)	((x & (1 << bit)) >> bit)	/* 获取第bit位 */
/*	RAWX协议 */
BOOL GetRAWXPtl(const U8* pData, U32 dataLen, SRAWX* pRAWX)
{
	S32 n = 0;           //用于解析时的字节计数
	if (pData == NULL)   //输入值判断
	{
		return FALSE;
	}

	n += 6;     //跳过帧头
	memcpy(&pRAWX->rcvTow, &pData[n], 8);
	n += 8;
	memcpy(&pRAWX->week, &pData[n], 2);
	n += 2;
	memcpy(&pRAWX->leaps, &pData[n], 1);
	n += 1;
	memcpy(&pRAWX->numMeas, &pData[n], 1);
	n += 1;
	pRAWX->leapSec = GET_BIT(pData[n], 0);
	pRAWX->clkReset = GET_BIT(pData[n], 1);
	n += 1;
	memcpy(&pRAWX->version, &pData[n], 1);
	n += 1;
	memcpy(&pRAWX->reserved0[0], &pData[n], 1);
	n += 1;
	memcpy(&pRAWX->reserved0[1], &pData[n], 1);
	n += 1;

	/*	写入消息内信息 */
	for (S32 i = 0; i < pRAWX->numMeas; i++)
	{
		memcpy(&pRAWX->aSRAWX[i].prMes, &pData[n], 8);
		n += 8;
		memcpy(&pRAWX->aSRAWX[i].cpMes, &pData[n], 8);
		n += 8;
		memcpy(&pRAWX->aSRAWX[i].doMes, &pData[n], 4);
		n += 4;
		memcpy(&pRAWX->aSRAWX[i].gnssID, &pData[n], 1);
		n += 1;
		memcpy(&pRAWX->aSRAWX[i].svID, &pData[n], 1);
		n += 1;
		memcpy(&pRAWX->aSRAWX[i].sigID, &pData[n], 1);
		n += 1;
		memcpy(&pRAWX->aSRAWX[i].freqID, &pData[n], 1);
		n += 1;
		memcpy(&pRAWX->aSRAWX[i].lockTime, &pData[n], 2);
		n += 2;
		memcpy(&pRAWX->aSRAWX[i].cno, &pData[n], 1);
		n += 1;
		pRAWX->aSRAWX[i].prStd = pData[n] & 0x0f;
		pRAWX->aSRAWX[i].prStdDev = 0.01 * ((F64)pow(2, pRAWX->aSRAWX[i].prStd));
		n += 1;
		pRAWX->aSRAWX[i].cpStd = pData[n] & 0x0f;
		pRAWX->aSRAWX[i].cpStdDev = 0.004 * ((F64)pRAWX->aSRAWX[i].cpStd);
		n += 1;
		pRAWX->aSRAWX[i].doStd = pData[n] & 0x0f;
		pRAWX->aSRAWX[i].doStdDev = 0.002 * ((F64)pow(2, pRAWX->aSRAWX[i].doStd));
		n += 1;
		pRAWX->aSRAWX[i].prValid = GET_BIT(pData[n], 0);
		pRAWX->aSRAWX[i].cpValid = GET_BIT(pData[n], 1);
		pRAWX->aSRAWX[i].halfCyc = GET_BIT(pData[n], 2);
		pRAWX->aSRAWX[i].subHalfCyc = GET_BIT(pData[n], 3);
		n += 1;
		memcpy(&pRAWX->aSRAWX[i].reserved1, &pData[n], 1);
		n += 1;
	}

	return TRUE;
}

/*	协议解析函数 */
BOOL GetDzPtl(const U8* pData, U32 dataLen, SDzNavInfo* pDzNavInfo)
{
	S32 n = 0;//代表整字节的计数
	S32 sum = 0;//代表校验和

	if (pData == NULL)
	{
		return FALSE;
	}
	if (dataLen != 570)
	{
		return FALSE;
	}

	//5-64字节
	{
		n += 4;
		memcpy(&pDzNavInfo->TicCount, &pData[n], 4);//5-8字节 TicCount
		n += 4;
		memcpy(&pDzNavInfo->timValdSym, &pData[n], 1);//9字节 时间有效标志
		n += 1;
		memcpy(&pDzNavInfo->timeYear, &pData[n], 2);//10-11字节 年
		n += 2;
		memcpy(&pDzNavInfo->timMonHour, &pData[n], 4);//12-15字节 月日时分
		n += 4;
		memcpy(&pDzNavInfo->timeSecnd, &pData[n], 8);//16-23字节 秒
		n += 8;
		memcpy(&pDzNavInfo->posStatus, &pData[n], 1);//24字节 定位状态
		n += 1;
		memcpy(&pDzNavInfo->locRest, &pData[n], 12);//25-36字节 代表定位结果XYZ
		n += 12;
		memcpy(&pDzNavInfo->locRestV, &pData[n], 12);//37-48字节 代表定位结果VXYZ
		n += 12;
		memcpy(&pDzNavInfo->locRestPdop, &pData[n], 2);//49-50字节 定位结果PDOP
		n += 2;
		memcpy(&pDzNavInfo->locRestHdop, &pData[n], 2);//51-52字节 定位结果HDOP
		n += 2;
		memcpy(&pDzNavInfo->locRestVdop, &pData[n], 2);//53-54字节 定位结果VDOP
		n += 2;
		memcpy(&pDzNavInfo->clokDiff, &pData[n], 4);//55-58字节 定位结果钟差
		n += 4;
		memcpy(&pDzNavInfo->clokFlot, &pData[n], 4);//59-62字节 定位结果钟漂
		n += 4;
		memcpy(&pDzNavInfo->chanNum, &pData[n], 1);//63字节 通道数
		n += 1;
		memcpy(&pDzNavInfo->softNum, &pData[n], 1);//64字节 软件版本号
		n += 1;
	}

	//每个卫星的数据，共24个通道，不足的用0补齐
	S32 i;
	for (i = 0; i < 24; i++)
	{
		memcpy(&pDzNavInfo->stInfo[i].satelLite, &pData[n], 1);//65字节 卫星号
		n += 1;
		memcpy(&pDzNavInfo->stInfo[i].sateStatus, &pData[n], 1);//66字节 卫星状态
		n += 1;
		memcpy(&pDzNavInfo->stInfo[i].chanStatus, &pData[n], 1);//67字节 通道状态
		n += 1;
		memcpy(&pDzNavInfo->stInfo[i].satelEve, &pData[n], 1);//68字节 卫星仰角
		n += 1;
		memcpy(&pDzNavInfo->stInfo[i].satelAdic, &pData[n], 2);//69-70字节 卫星方位角
		n += 2;
		memcpy(&pDzNavInfo->stInfo[i].signalRatio, &pData[n], 1);//71字节 信噪比
		n += 1;
		memcpy(&pDzNavInfo->stInfo[i].doppler, &pData[n], 4);//72-75字节 多普勒
		n += 4;
		memcpy(&pDzNavInfo->stInfo[i].chancode_doc_phase, &pData[n], 2);//76-77字节 通道code_doc_phase
		n += 2;
		memcpy(&pDzNavInfo->stInfo[i].chancode_phase, &pData[n], 4);//78-81字节 通道code_phase
		n += 4;
		memcpy(&pDzNavInfo->stInfo[i].bitState, &pData[n], 2);//82-83字节 比特位同步状态
		n += 2;

	}

	memcpy(&pDzNavInfo->obligate, &pData[520], 48);//(N-1)*19+84-(N-1)*19+131字节 预留
	n += 48;
	memcpy(&pDzNavInfo->checksum, &pData[568], 2);//(N-1)*19+132-(N-1)*19+133字节 校验和
	n += 2;

	//校验一下
	for (S32 i = 0; i < 568; i++)
	{
		sum += pData[i];
	}
	if (sum != pDzNavInfo->checksum)
	{
		return FALSE;
	}

	return TRUE;
}


